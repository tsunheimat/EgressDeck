import { expect, test } from '@playwright/test'
import { signIn } from './auth'

test('Chinese dashboard, evidence boundaries, and responsive keyboard navigation', async ({ page, context }, testInfo) => {
  const pageErrors: string[] = []
  page.on('pageerror', error => pageErrors.push(error.message))
  await signIn(context)
  await page.setViewportSize({ width: 1408, height: 1056 })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '总览', exact: true, level: 1 })).toBeVisible()
  await expect(page.locator('.dashboard')).toHaveAttribute('aria-busy', 'false')
  await expect(page.getByRole('navigation', { name: '主导航' }).getByRole('button')).toHaveText(['总览', '代理', '订阅', '设备与分组', '规则策略', '基础设施', '活动与诊断'])
  await expect(page.locator('[data-step="verification"]')).toHaveAttribute('data-state', 'unknown')
  await expect(page.locator('.coverage-ring')).toContainText('待验证')
  await expect(page).toHaveTitle('总览 · EgressDeck')
  await expect(page.getByRole('combobox', { name: '默认操作网关' })).toHaveValue('fixture-gateway')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(1408)
  await page.screenshot({ path: testInfo.outputPath('overview-desktop.png'), fullPage: true })

  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('navigation', { name: '主导航' })).toBeHidden()
  const menu = page.getByRole('button', { name: '打开导航', exact: true })
  await menu.click()
  const drawer = page.getByRole('dialog', { name: '导航菜单' })
  await expect(drawer).toBeVisible()
  const close = drawer.getByRole('button', { name: '关闭导航' })
  await expect(close).toBeFocused()
  await expect(page.locator('.workspace')).toHaveAttribute('inert', '')
  await page.keyboard.press('Shift+Tab')
  await expect(drawer.getByRole('button', { name: '刷新控制器状态' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(drawer).toBeHidden()
  await expect(menu).toBeFocused()

  await menu.click()
  await drawer.getByRole('button', { name: '设备与分组', exact: true }).click()
  await expect(page.getByRole('heading', { name: '设备与分组', level: 1 })).toBeVisible()
  await expect(page.getByRole('main')).toBeFocused()
  await expect(drawer).toBeHidden()
  await menu.click()
  await drawer.getByRole('button', { name: '总览', exact: true }).click()
  await expect(page.locator('.dashboard')).toHaveAttribute('aria-busy', 'false')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: testInfo.outputPath('overview-mobile.png'), fullPage: true })
  await page.setViewportSize({ width: 320, height: 740 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
  expect(pageErrors).toEqual([])
})

test('signed-out shell requires authentication rather than displaying sample success', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '登录 EgressDeck' })).toBeVisible()
  await expect(page.locator('.dashboard')).toHaveCount(0)
  await expect(page.getByRole('link', { name: '通过单点登录继续' })).toHaveAttribute('href', /auth\/oidc\/login/)
})
